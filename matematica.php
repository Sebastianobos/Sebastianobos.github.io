<p style="font-style:oblique;">Supervisor: Umberto Zannier</p>
<!--<a style="font-size:50px;" href="tesi_Boscardin.pdf"> &#8594</a>-->
<p>
I'm studying the equation f(a^m,y)=b^n with solutions (y,m,n) all integers. f is a polynomial with coefficients in Q, and a and b are integer parameters. There are only finitely many solutions if we assume some technical hypotheses. This was proved by Zannier and Corvaja.
<br>
My goal is to prove the same when a number field replaces Q, and to weaken some hypotheses in same cases. The main tool is the <a href="https://en.wikipedia.org/wiki/Subspace_theorem#:~:text=In%20mathematics%2C%20the%20subspace%20theorem,Schmidt%20(1972)."> Subspace Theorem</a>. <a href="tesi_boscardin.pdf">Here</a> it is my master thesis.
</p>
